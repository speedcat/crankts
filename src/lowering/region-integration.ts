import type { IrFunction, IrModule, IrStruct, IrType } from "./ir.js";
import type { RegionPlan } from "./region.js";
import { guardExpression, inputSpec, wrapperRuntime, type InputSpec } from "./wrapper-ts.js";

/**
 * Integration and parity generation for extracted regions (v0.2.5).
 *
 * `ts/integration.ts` exports one function per execute region, called by the patched source with the
 * original local names. It keeps the prepared native state per owner (`this`) and reuses it only while
 * the prepare inputs equal their snapshot (CONTENT_SNAPSHOT, compared on every call). In-out maps
 * cross as their keys; the kernel's ordered set-log is replayed into the caller's map only after the
 * kernel succeeded, so a trap leaves the map untouched and the outlined TypeScript runs instead.
 * Fallback reasons are the same as for wrappers (ADDON_MISSING, CONTRACT_GUARD, CRANKTS_KERNEL_TRAP);
 * any other native failure surfaces as CRANKTS_INTERNAL_ERROR.
 */

export interface RegionIntegrationRequest {
  readonly plan: RegionPlan;
  readonly crateName: string;
  readonly execute: IrModule;
  readonly prepare?: IrModule;
}

export function emitRegionIntegration(request: RegionIntegrationRequest): ReadonlyMap<string, string> {
  const { plan } = request;
  const library = request.crateName.replace(/-/g, "_");
  const envVariable = `CRANKTS_ADDON_${library.toUpperCase()}`;
  const execute = entryOf(request.execute);
  const prepare = request.prepare ? entryOf(request.prepare) : undefined;
  const structs = new Map([...request.execute.structs, ...(request.prepare?.structs ?? [])].map((struct) => [struct.name, struct]));
  return new Map([
    ["ts/integration.ts", integration(plan, execute, prepare, structs, library, envVariable)],
    ["ts/parity.ts", parity(plan, execute, prepare, structs)],
  ]);
}

function entryOf(module: IrModule): IrFunction {
  const entry = module.functions.find((fn) => fn.name === module.entry);
  if (!entry) {
    throw new Error(`IR module has no entry ${module.entry}`);
  }
  return entry;
}

/** Expression that rebuilds the map value at log row `index` (struct fields in declaration order). */
function replayValue(type: IrType, structs: ReadonlyMap<string, IrStruct>, log: string, index: string): string {
  if (type.kind === "struct") {
    const struct = structs.get(type.name);
    return `{ ${(struct?.fields ?? []).map((field) => `${field.name}: ${log}.${field.name}[${index}]`).join(", ")} }`;
  }
  return `${log}.value[${index}]`;
}

function integration(
  plan: RegionPlan,
  execute: IrFunction,
  prepare: IrFunction | undefined,
  structs: ReadonlyMap<string, IrStruct>,
  library: string,
  envVariable: string,
): string {
  const executeParams = plan.executeParams.filter((param) => param.role !== "state");
  const signature = executeParams.map((param) => `${param.name}: ${param.sourceType}`).join(", ");
  const prepareTuple = `[${plan.prepareParams.map((param) => param.sourceType).join(", ")}]`;
  const inout = plan.executeParams.find((param) => param.role === "inout");
  const inoutType = execute.params.find((param) => param.name === inout?.name)?.type;
  const prepareSpecs = prepare?.params.map((param) => inputSpec(param.type)) ?? [];
  const executeGuards = executeParams.map((param) => {
    if (param.role === "inout") {
      return `${param.name} instanceof Map && [...${param.name}.keys()].every((key) => typeof key === "string")`;
    }
    const type = execute.params.find((candidate) => candidate.name === param.name)?.type;
    return type ? guardExpression(inputSpec(type), param.name) : "false";
  });
  const nativeArgs = plan.executeParams.map((param) => (
    param.role === "state" ? "entry.handle" : param.role === "inout" ? `Array.from(${param.name}.keys())` : param.name
  ));
  const typescriptArgs = plan.executeParams.map((param) => (param.role === "state" ? "typescriptState(entry)" : param.name));
  const prepareName = plan.prepareName ?? "";
  const stateType = plan.stateName ?? "unknown";

  return `// Generated by CrankTS (v0.2.5 region integration). Do not edit; regenerate with \`crankts extract\`.
// Called by the patched source in place of ${plan.function} lines of the execute region. The outlined
// regions in ./regions.ts are the exact TypeScript fallback.
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { ${prepare ? `${prepareName} as typescript_${prepareName}, ` : ""}${plan.executeName} as typescript_${plan.executeName}${plan.stateName ? `, type ${plan.stateName}` : ""} } from "./regions.js";

${wrapperRuntime(library, envVariable, false)}

/** Prepared states built (cache misses: first use, or prepare inputs changed). */
export const regionStatus = { preparations: 0, cacheHits: 0 };

interface Entry {
  /** Snapshot of the prepare inputs; the native state is valid exactly while they are equal. */
  readonly inputs: ${prepareTuple};
  /** CONTRACT_GUARD on the prepare inputs, checked once per preparation (not on every call). */
  readonly inContract: boolean;
  handle: unknown;
  prepareFailed: boolean;
  state: ${stateType} | undefined;
}

const entries = new WeakMap<object, Entry>();
const moduleOwner = {};

function snapshot<T>(value: T): T {
  if (Array.isArray(value)) {
    return [...value] as T;
  }
  return ArrayBuffer.isView(value) && "slice" in value ? (value as unknown as { slice(): T }).slice() : value;
}

/** Value equality of prepare inputs (arrays and typed arrays element-wise, scalars with Object.is). */
function sameInput(left: unknown, right: unknown): boolean {
  if (Object.is(left, right)) {
    return true;
  }
  if ((Array.isArray(left) && Array.isArray(right)) || (ArrayBuffer.isView(left) && ArrayBuffer.isView(right))) {
    const a = left as ArrayLike<unknown>;
    const b = right as ArrayLike<unknown>;
    if (a.length !== b.length) return false;
    for (let index = 0; index < a.length; index += 1) {
      if (!Object.is(a[index], b[index])) return false;
    }
    return true;
  }
  return false;
}

function typescriptState(entry: Entry): ${stateType} {
  ${prepare ? `entry.state ??= typescript_${prepareName}(...entry.inputs);
  return entry.state;` : "return undefined as never;"}
}

${guardsFunction("prepareInContract", prepareSpecs)}

export function ${plan.executeName}(owner: object | undefined, prepareInputs: ${prepareTuple}, ${signature}): void {
  const key = owner ?? moduleOwner;
  let entry = entries.get(key);
  if (entry && prepareInputs.every((input, index) => sameInput(input, entry?.inputs[index]))) {
    regionStatus.cacheHits += 1;
  } else {
    const inputs = prepareInputs.map(snapshot) as ${prepareTuple};
    entry = { inputs, inContract: prepareInContract(inputs), handle: undefined, prepareFailed: false, state: undefined };
    entries.set(key, entry);
    regionStatus.preparations += 1;
  }
  const prepare = nativeAddon?.["${prepareName}"];
  const kernel = nativeAddon?.["${execute.name}"];
  if (prepare && kernel) {
    if (!entry.inContract || !(${executeGuards.join("\n      && ")})) {
      nativeStatus.contractGuards += 1;
    } else {
      try {
        if (entry.handle === undefined && !entry.prepareFailed) {
          entry.handle = prepare(...entry.inputs);
          nativeStatus.nativeCalls += 1;
        }
        if (entry.handle !== undefined) {
          ${inout ? `const log = kernel(${nativeArgs.join(", ")}) as Record<string, unknown[]> & { keys: string[] };
          nativeStatus.nativeCalls += 1;
          // Replay only after success: a trap above leaves ${inout.name} untouched.
          for (let index = 0; index < log.keys.length; index += 1) {
            ${inout.name}.set(log.keys[index] as string, ${inoutType?.kind === "map" ? replayValue(inoutType.value, structs, "log", "index") : "undefined"} as never);
          }` : `kernel(${nativeArgs.join(", ")});
          nativeStatus.nativeCalls += 1;`}
          return;
        }
      } catch (error) {
        if (entry.handle === undefined) {
          entry.prepareFailed = true;
        }
        handleNativeFailure(error, "${execute.name}");
      }
    }
  }
  typescript_${plan.executeName}(${typescriptArgs.join(", ")});
}
`;
}

function guardsFunction(name: string, specs: readonly InputSpec[]): string {
  const checks = specs.map((spec, index) => guardExpression(spec, `args[${index}]`));
  return `function ${name}(args: readonly unknown[]): boolean {
  return args.length === ${specs.length}${checks.map((check) => `\n    && ${check}`).join("")};
}`;
}

// --- parity -------------------------------------------------------------------------------------

function parity(plan: RegionPlan, execute: IrFunction, prepare: IrFunction | undefined, structs: ReadonlyMap<string, IrStruct>): string {
  const specs = {
    prepare: prepare?.params.map((param) => inputSpec(param.type)) ?? [],
    execute: plan.executeParams.map((param) => {
      if (param.role === "state") return { kind: "state" };
      const type = execute.params.find((candidate) => candidate.name === param.name)?.type;
      if (param.role === "inout" && type?.kind === "map") {
        return { kind: "inoutMap", value: type.value.kind === "struct" ? { kind: "struct", fields: structs.get(type.value.name)?.fields.map((field) => ({ name: field.name, spec: inputSpec(field.type) })) ?? [] } : inputSpec(type.value) };
      }
      return type ? inputSpec(type) : { kind: "f64" };
    }),
  };
  const stateIndex = plan.executeParams.findIndex((param) => param.role === "state");
  const inoutIndex = plan.executeParams.findIndex((param) => param.role === "inout");
  return `// Generated by CrankTS (v0.2.5 region parity runner). Do not edit; regenerate with \`crankts extract\`.
// For every case, the final in-out map must be identical (entries, order, values) for:
//   1. the outlined TypeScript regions (the reference),
//   2. the integration (native with fallback), called twice on one owner (cache miss, then cache hit),
//   3. the raw addon plus replay — unless it traps (CRANKTS_KERNEL_TRAP).
// Run: node --import tsx parity.ts [--iterations 1000] [--seed 1]
import { pathToFileURL } from "node:url";
import * as regions from "./regions.js";
import * as integration from "./integration.js";

const SPECS = ${JSON.stringify(specs, null, 2)} as const;
const STATE_INDEX = ${stateIndex};
const INOUT_INDEX = ${inoutIndex};

type Spec = { readonly kind: string; readonly element?: Spec; readonly storage?: string; readonly value?: Spec; readonly fields?: readonly { name: string; spec: Spec }[] };

export interface RegionParityReport {
  readonly cases: number;
  readonly nativeAvailable: boolean;
  readonly nativeAgreed: number;
  readonly nativeTrapped: number;
  readonly mismatches: readonly string[];
}

const WORDS = ["graph", "Graph", "GRAPH", "node", "Node_1", "kwx", "KWX", "scan", "Tarjan", "map", "a", "ab", "x9", "_id"];
const NOISE = [" ", ". ", "-", "\\n", "é", "😀", "\\uD800", "(", ")", "a+b", "state machine"];

function random(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state * 1664525 + 1013904223) >>> 0;
    return state / 2 ** 32;
  };
}

function generate(spec: Spec, next: () => number): unknown {
  const pick = <T>(values: readonly T[]): T => values[Math.floor(next() * values.length)] as T;
  switch (spec.kind) {
    case "f64":
      return Math.floor(next() * 12);
    case "bool":
      return next() < 0.5;
    case "string":
      return Array.from({ length: Math.floor(next() * 14) }, () => (next() < 0.6 ? pick(WORDS) : pick(NOISE))).join("");
    case "array":
      return Array.from({ length: Math.floor(next() * 10) }, () => (
        spec.element?.kind === "string" ? (next() < 0.8 ? pick(WORDS) : pick(NOISE)) : generate(spec.element ?? { kind: "f64" }, next)
      ));
    case "struct":
      return Object.fromEntries((spec.fields ?? []).map((field) => [field.name, generate(field.spec, next)]));
    case "inoutMap": {
      const map = new Map<string, unknown>();
      for (let index = Math.floor(next() * 3); index > 0; index -= 1) {
        map.set(pick(WORDS), generate(spec.value ?? { kind: "f64" }, next));
      }
      return map;
    }
    default:
      return undefined;
  }
}

function cloneMap(value: unknown): unknown {
  return value instanceof Map ? new Map([...value].map(([key, entry]) => [key, typeof entry === "object" && entry ? { ...entry } : entry])) : value;
}

function same(left: unknown, right: unknown): boolean {
  if (Object.is(left, right)) return true;
  if (left instanceof Map && right instanceof Map) {
    const a = [...left];
    const b = [...right];
    return a.length === b.length && a.every(([key, value], index) => key === b[index]?.[0] && same(value, b[index]?.[1]));
  }
  if (Array.isArray(left) && Array.isArray(right)) {
    return left.length === right.length && left.every((value, index) => same(value, right[index]));
  }
  if (left && right && typeof left === "object" && typeof right === "object") {
    const leftKeys = Object.keys(left);
    const rightKeys = Object.keys(right);
    return leftKeys.length === rightKeys.length && leftKeys.every((key, index) => key === rightKeys[index]
      && same((left as Record<string, unknown>)[key], (right as Record<string, unknown>)[key]));
  }
  return false;
}

export function runRegionParity(options: { readonly iterations?: number; readonly seed?: number } = {}): RegionParityReport {
  const next = random(options.seed ?? 1);
  const addon = integration.nativeAddon;
  let nativeAgreed = 0;
  let nativeTrapped = 0;
  const mismatches: string[] = [];
  const iterations = options.iterations ?? 1000;
  for (let iteration = 0; iteration < iterations; iteration += 1) {
    const prepareArgs = SPECS.prepare.map((spec) => generate(spec as Spec, next));
    const executeArgs = SPECS.execute.map((spec) => generate(spec as Spec, next));
    const run = (args: unknown[]): unknown[] => args.map(cloneMap);

    const expectedArgs = run(executeArgs);
    ${prepare ? `if (STATE_INDEX >= 0) expectedArgs[STATE_INDEX] = (regions as Record<string, (...args: unknown[]) => unknown>)["${plan.prepareName}"]?.(...prepareArgs);` : ""}
    (regions as Record<string, (...args: unknown[]) => unknown>)["${plan.executeName}"]?.(...expectedArgs);
    const expected = expectedArgs[INOUT_INDEX];

    const owner = {};
    for (const pass of ["miss", "hit"]) {
      const viaIntegration = run(executeArgs).filter((_, index) => index !== STATE_INDEX);
      (integration as unknown as Record<string, (...args: unknown[]) => unknown>)["${plan.executeName}"]?.(owner, prepareArgs, ...viaIntegration);
      const actual = viaIntegration[INOUT_INDEX - (STATE_INDEX >= 0 && STATE_INDEX < INOUT_INDEX ? 1 : 0)];
      if (!same(expected, actual)) mismatches.push(\`integration (\${pass}) case \${iteration}\`);
    }

    if (addon) {
      try {
        const nativeArgs = run(executeArgs);
        const target = nativeArgs[INOUT_INDEX] as Map<string, unknown>;
        ${prepare ? `if (STATE_INDEX >= 0) nativeArgs[STATE_INDEX] = addon["${prepare.name}"]?.(...prepareArgs);` : ""}
        nativeArgs[INOUT_INDEX] = Array.from(target.keys());
        const log = addon["${execute.name}"]?.(...nativeArgs) as Record<string, unknown[]> & { keys: string[] };
        for (let index = 0; index < log.keys.length; index += 1) {
          const value = Object.keys(log).filter((column) => column !== "keys");
          target.set(log.keys[index] as string, value.length === 1 && value[0] === "value"
            ? log.value?.[index]
            : Object.fromEntries(value.map((column) => [column, log[column]?.[index]])));
        }
        if (same(expected, target)) nativeAgreed += 1;
        else mismatches.push(\`native case \${iteration}\`);
      } catch (error) {
        if (String(error instanceof Error ? error.message : error).startsWith("CRANKTS_KERNEL_TRAP")) nativeTrapped += 1;
        else mismatches.push(\`native case \${iteration}: \${error instanceof Error ? error.message : String(error)}\`);
      }
    }
  }
  return { cases: iterations, nativeAvailable: addon !== undefined, nativeAgreed, nativeTrapped, mismatches };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const argv = process.argv.slice(2);
  const option = (name: string): string | undefined => argv[argv.indexOf(name) + 1];
  const report = runRegionParity({ iterations: Number(option("--iterations") ?? 1000), seed: Number(option("--seed") ?? 1) });
  console.log(JSON.stringify({ ...report, mismatches: report.mismatches.slice(0, 5), nativeStatus: integration.nativeStatus, regionStatus: integration.regionStatus }, null, 2));
  process.exitCode = report.mismatches.length > 0 ? 1 : 0;
}
`;
}
