import type { KernelContract } from "./contract.js";
import type { IrExpr, IrFunction, IrModule, IrStmt, IrStruct, IrType } from "./ir.js";
import { isReferenceType } from "./ir.js";
import { analyzeOrigins, type OriginAnalysis } from "./verify.js";

/**
 * Rust/N-API backend (v0.2.2). Emits a napi-rs crate whose behavior equals `interpretIr`: the same
 * results, and a `CRANKTS_KERNEL_TRAP` error wherever the interpreter raises `KernelTrap`.
 *
 * Storage follows the verifier's origin analysis: fresh storage is owned (`Vec`, `HashMap`, structs),
 * parameter-derived storage is borrowed. NO_ALIASING (required by a lowerable contract) is what makes
 * owned values equivalent to JavaScript references. Strings are `Rc<[u16]>`, so every position is a
 * UTF-16 code unit, exactly as in JS.
 */

export interface RustCrate {
  readonly files: ReadonlyMap<string, string>;
}

export interface RustBackendRequest {
  readonly crateName: string;
  readonly contract: KernelContract;
  readonly execute: IrModule;
  readonly prepare?: IrModule;
}

export class RustBackendError extends Error {}

export const KERNEL_TRAP_PREFIX = "CRANKTS_KERNEL_TRAP";
const NAPI_VERSION = "3.14.2";
const NAPI_DERIVE_VERSION = "3.6.12";

export function emitRustCrate(request: RustBackendRequest): RustCrate {
  const module = mergeModules(request.execute, request.prepare);
  const origins = analyzeOrigins(module);
  const emitter = new RustEmitter(module, origins);
  const lines = [
    "// Generated by CrankTS (v0.2.2 Rust/N-API backend). Do not edit; regenerate with `crankts extract`.",
    `// Contract: ${request.contract.name} (${request.contract.shape})`,
    RUNTIME,
    ...module.structs.map((struct) => emitter.struct(struct)),
    ...module.functions.map((fn) => emitter.function(fn)),
    ...napiSurface(request, module),
  ];
  return {
    files: new Map([
      ["Cargo.toml", cargoToml(request.crateName)],
      ["src/lib.rs", `${lines.join("\n\n")}\n`],
    ]),
  };
}

/** PREPARED_STATE lowers two modules that may share helpers and structs; they must agree. */
function mergeModules(execute: IrModule, prepare?: IrModule): IrModule {
  if (!prepare) {
    return execute;
  }
  const functions = new Map(prepare.functions.map((fn) => [fn.name, fn]));
  for (const fn of execute.functions) {
    const existing = functions.get(fn.name);
    if (existing && JSON.stringify(existing) !== JSON.stringify(fn)) {
      throw new RustBackendError(`prepare and execute define different functions named ${fn.name}`);
    }
    functions.set(fn.name, fn);
  }
  const structs = new Map(prepare.structs.map((struct) => [struct.name, struct]));
  for (const struct of execute.structs) {
    const existing = structs.get(struct.name);
    if (existing && JSON.stringify(existing) !== JSON.stringify(struct)) {
      throw new RustBackendError(`prepare and execute define different structs named ${struct.name}`);
    }
    structs.set(struct.name, struct);
  }
  return { irVersion: 1, entry: execute.entry, functions: [...functions.values()], structs: [...structs.values()] };
}

function cargoToml(crateName: string): string {
  return `[package]
name = "${crateName}"
version = "0.1.0"
edition = "2021"
publish = false

[lib]
crate-type = ["cdylib"]

[dependencies]
napi = { version = "${NAPI_VERSION}", default-features = false, features = ["napi8", "dyn-symbols"] }
napi-derive = "${NAPI_DERIVE_VERSION}"

[profile.release]
opt-level = 3
lto = true
codegen-units = 1

[workspace]
`;
}

const RUNTIME = String.raw`#![allow(unused_imports, unused_mut, unused_variables, unused_parens, unused_braces, unreachable_code, non_snake_case, non_camel_case_types, dead_code, clippy::all)]

use std::collections::HashMap;
use std::rc::Rc;
use std::sync::atomic::{AtomicU64, Ordering};

use napi::bindgen_prelude::*;
use napi_derive::napi;

// ---- Kernel IR runtime: checked operations trap instead of emulating JS edge cases ----

type Str = Rc<[u16]>;

pub struct Trap(String);
type R<T> = std::result::Result<T, Trap>;

#[cold]
fn trap<T>(reason: &str) -> R<T> {
  Err(Trap(reason.to_string()))
}

fn trap_error(trap: Trap) -> napi::Error {
  napi::Error::new(Status::GenericFailure, format!("CRANKTS_KERNEL_TRAP: {}", trap.0))
}

static ITERATION_BUDGET: AtomicU64 = AtomicU64::new(u64::MAX);

/// TERMINATION guard: total while-loop iterations per kernel call.
#[napi(js_name = "__setIterationBudget")]
pub fn set_iteration_budget(budget: f64) {
  let value = if budget.is_nan() || budget < 0.0 { 0 } else if budget >= u64::MAX as f64 { u64::MAX } else { budget as u64 };
  ITERATION_BUDGET.store(value, Ordering::Relaxed);
}

struct Ctx {
  remaining: u64,
}

impl Ctx {
  fn new() -> Self {
    Ctx { remaining: ITERATION_BUDGET.load(Ordering::Relaxed) }
  }

  #[inline]
  fn tick(&mut self) -> R<()> {
    if self.remaining == 0 {
      return trap("iteration budget exhausted");
    }
    self.remaining -= 1;
    Ok(())
  }
}

#[inline]
fn idx(value: f64, length: usize, operation: &str) -> R<usize> {
  if value >= 0.0 && value < length as f64 && value.fract() == 0.0 {
    Ok(value as usize)
  } else {
    trap(operation)
  }
}

#[inline]
fn array_length(value: f64) -> R<usize> {
  // Same limit as the interpreter (2^28): larger allocations trap instead of aborting on OOM.
  if value >= 0.0 && value <= 268435456.0 && value.fract() == 0.0 {
    Ok(value as usize)
  } else {
    trap("array length")
  }
}

#[inline]
fn store_u8(value: f64) -> R<u8> {
  if value >= 0.0 && value <= 255.0 && value.fract() == 0.0 { Ok(value as u8) } else { trap("value does not fit Uint8Array") }
}

#[inline]
fn store_u32(value: f64) -> R<u32> {
  if value >= 0.0 && value <= 4294967295.0 && value.fract() == 0.0 { Ok(value as u32) } else { trap("value does not fit Uint32Array") }
}

#[inline]
fn store_i32(value: f64) -> R<i32> {
  if value >= -2147483648.0 && value <= 2147483647.0 && value.fract() == 0.0 { Ok(value as i32) } else { trap("value does not fit Int32Array") }
}

#[inline]
fn store_f64(value: f64) -> R<f64> {
  Ok(value)
}

/// Math.min semantics: NaN wins, -0 < +0.
#[inline]
fn js_min(left: f64, right: f64) -> f64 {
  if left.is_nan() || right.is_nan() {
    f64::NAN
  } else if left == right {
    if left.is_sign_negative() { left } else { right }
  } else if left < right {
    left
  } else {
    right
  }
}

/// Math.max semantics: NaN wins, +0 > -0.
#[inline]
fn js_max(left: f64, right: f64) -> f64 {
  if left.is_nan() || right.is_nan() {
    f64::NAN
  } else if left == right {
    if left.is_sign_positive() { left } else { right }
  } else if left > right {
    left
  } else {
    right
  }
}

#[inline]
fn char_code_at(text: &[u16], index: f64) -> R<f64> {
  Ok(text[idx(index, text.len(), "charCodeAt index")?] as f64)
}

fn slice(text: &[u16], start: f64, end: f64) -> R<Str> {
  if start >= 0.0 && start <= end && end <= text.len() as f64 && start.fract() == 0.0 && end.fract() == 0.0 {
    Ok(Rc::from(&text[start as usize..end as usize]))
  } else {
    trap("slice bounds")
  }
}

fn to_lower_ascii(text: &[u16]) -> R<Str> {
  let mut lowered = Vec::with_capacity(text.len());
  for &unit in text {
    if unit >= 128 {
      return trap("toLowerAscii on a non-ASCII string");
    }
    lowered.push(if (65..=90).contains(&unit) { unit + 32 } else { unit });
  }
  Ok(Rc::from(lowered))
}

fn str_literal(units: &[u16]) -> Str {
  Rc::from(units)
}`;

class RustEmitter {
  private readonly functions: ReadonlyMap<string, IrFunction>;
  private readonly structFields: ReadonlyMap<string, ReadonlyMap<string, IrType>>;
  private current: IrFunction | undefined;
  private scopes: Map<string, IrType>[] = [];
  private temp = 0;

  constructor(module: IrModule, private readonly origins: OriginAnalysis) {
    this.functions = new Map(module.functions.map((fn) => [fn.name, fn]));
    this.structFields = new Map(module.structs.map((struct) => [struct.name, new Map(struct.fields.map((field) => [field.name, field.type]))]));
  }

  struct(struct: IrStruct): string {
    const fields = struct.fields.map((field) => `  pub f_${field.name}: ${ownedType(field.type)},`);
    return `#[derive(Clone, Debug)]\npub struct K_${struct.name} {\n${fields.join("\n")}\n}`;
  }

  function(fn: IrFunction): string {
    this.current = fn;
    this.scopes = [new Map(fn.params.map((param) => [param.name, param.type]))];
    const params = ["ctx: &mut Ctx", ...fn.params.map((param) => `l_${param.name}: ${paramType(param.type)}`)];
    const body = this.block(fn.body, 1);
    const tail = fn.returnType.kind === "void" ? "  Ok(())" : `  trap("missing return")`;
    return `fn f_${fn.name}(${params.join(", ")}) -> R<${returnType(fn.returnType)}> {\n${body}\n${tail}\n}`;
  }

  // --- statements -----------------------------------------------------------------------------

  private block(body: readonly IrStmt[], depth: number): string {
    this.scopes.push(new Map());
    const lines = body.map((statement) => this.statement(statement, depth));
    this.scopes.pop();
    return lines.join("\n");
  }

  private statement(statement: IrStmt, depth: number): string {
    const pad = "  ".repeat(depth);
    switch (statement.stmt) {
      case "let": {
        this.scopes[this.scopes.length - 1]?.set(statement.name, statement.type);
        if (isReferenceType(statement.type) && this.localOrigin(statement.name) === "PARAM") {
          return `${pad}let mut l_${statement.name} = &${this.place(statement.init)};`;
        }
        return `${pad}let mut l_${statement.name}: ${ownedType(statement.type)} = ${this.value(statement.init, statement.type)};`;
      }
      case "assign": {
        const type = this.lookup(statement.name);
        if (isReferenceType(type) && this.localOrigin(statement.name) === "PARAM") {
          return `${pad}l_${statement.name} = &${this.place(statement.value)};`;
        }
        return `${pad}l_${statement.name} = ${this.value(statement.value, type)};`;
      }
      case "setIndex": {
        const target = this.place(statement.target);
        const type = this.typeOf(statement.target);
        if (type.kind !== "array") {
          throw new RustBackendError("setIndex on a non-array");
        }
        const index = this.fresh("index");
        const value = this.fresh("value");
        return `${pad}{ let ${index} = idx(${this.scalar(statement.index)}, ${target}.len(), "setIndex index")?; `
          + `let ${value} = ${this.storeValue(statement.value, type)}; ${target}[${index}] = ${value}; }`;
      }
      case "push": {
        const type = this.typeOf(statement.target);
        if (type.kind !== "array" || type.storage !== "dynamic") {
          return `${pad}return trap("push on a typed array");`;
        }
        const value = this.fresh("value");
        return `${pad}{ let ${value} = ${this.value(statement.value, type.element)}; ${this.place(statement.target)}.push(${value}); }`;
      }
      case "pop": {
        const type = this.typeOf(statement.target);
        if (type.kind !== "array" || type.storage !== "dynamic") {
          return `${pad}return trap("pop on a typed array");`;
        }
        return `${pad}if ${this.place(statement.target)}.pop().is_none() { return trap("pop on an empty array"); }`;
      }
      case "clear": {
        const type = this.typeOf(statement.target);
        if (type.kind !== "array" || type.storage !== "dynamic") {
          return `${pad}return trap("clear on a typed array");`;
        }
        return `${pad}${this.place(statement.target)}.clear();`;
      }
      case "mapSet": {
        const key = this.fresh("key");
        const value = this.fresh("value");
        return `${pad}{ let ${key} = ${this.value(statement.key, { kind: "string" })}; let ${value} = ${this.scalar(statement.value)}; `
          + `${this.place(statement.map)}.insert(${key}, ${value}); }`;
      }
      case "sortByKeys": {
        const keys = statement.keys.map((key) => ({ name: this.fresh("key"), code: this.place(key) }));
        const element = this.fresh("element");
        const target = this.place(statement.target);
        const checks = keys.map((key) => `idx(${element} as f64, ${key.name}.len(), "sortByKeys key")?;`).join(" ");
        const compare = keys
          .map((key) => `${key.name}[left as usize].cmp(&${key.name}[right as usize])`)
          .reduce((chain, next) => `${chain}.then_with(|| ${next})`);
        return [
          `${pad}{`,
          ...keys.map((key) => `${pad}  let ${key.name} = &${key.code};`),
          `${pad}  for &${element} in ${target}.iter() { ${checks} }`,
          `${pad}  ${target}.sort_by(|&left, &right| ${compare});`,
          `${pad}}`,
        ].join("\n");
      }
      case "if":
        return `${pad}if ${this.scalar(statement.test)} {\n${this.block(statement.then, depth + 1)}\n${pad}}`
          + (statement.otherwise.length > 0 ? ` else {\n${this.block(statement.otherwise, depth + 1)}\n${pad}}` : "");
      case "block":
        return `${pad}{\n${this.block(statement.body, depth + 1)}\n${pad}}`;
      case "while":
        return `${pad}while ${this.scalar(statement.test)} {\n${pad}  ctx.tick()?;\n${this.block(statement.body, depth + 1)}\n${pad}}`;
      case "forRange": {
        const end = this.fresh("end");
        const counter = this.fresh("counter");
        this.scopes.push(new Map([[statement.variable, { kind: "f64" }]]));
        const body = this.block(statement.body, depth + 2);
        this.scopes.pop();
        return [
          `${pad}{`,
          `${pad}  let ${end}: f64 = ${this.scalar(statement.end)};`,
          `${pad}  let mut ${counter}: f64 = ${this.scalar(statement.start)};`,
          `${pad}  while ${counter} < ${end} {`,
          `${pad}    let l_${statement.variable}: f64 = ${counter};`,
          `${pad}    ${counter} += 1.0;`,
          body,
          `${pad}  }`,
          `${pad}}`,
        ].join("\n");
      }
      case "break":
        return `${pad}break;`;
      case "continue":
        return `${pad}continue;`;
      case "return":
        return statement.value
          ? `${pad}return Ok(${this.value(statement.value, this.current?.returnType ?? this.typeOf(statement.value))});`
          : `${pad}return Ok(());`;
      case "expr":
        return `${pad}let _ = ${this.value(statement.value, this.typeOf(statement.value))};`;
    }
  }

  // --- expressions ----------------------------------------------------------------------------

  /** An owned value of `type` (scalars, `Str` clones, fresh storage moved, parameter storage copied). */
  private value(expr: IrExpr, type: IrType): string {
    if (!isReferenceType(type)) {
      return type.kind === "string" ? this.string(expr) : this.scalar(expr);
    }
    switch (expr.op) {
      case "arrayNew": {
        const length = `array_length(${this.scalar(expr.length)})?`;
        return `vec![${this.storeValue(expr.fill, expr.type)}; ${length}]`;
      }
      case "arrayLiteral":
        return `vec![${expr.elements.map((element) => this.storeValue(element, expr.type)).join(", ")}]`;
      case "mapNew":
        return "HashMap::new()";
      case "struct":
        return `K_${expr.name} { ${expr.fields.map((field) => `f_${field.name}: ${this.value(field.value, this.fieldType(expr.name, field.name))}`).join(", ")} }`;
      case "call":
        return this.call(expr);
      default:
        // Fresh locals move out (NO_ALIASING: only in return or struct literals that are returned);
        // parameter-derived storage is copied.
        return this.originOf(expr) === "FRESH" && expr.op === "local"
          ? `l_${expr.name}`
          : `${this.place(expr)}.to_owned()`;
    }
  }

  /** A place expression for reference-typed storage (borrowable and, for fresh storage, mutable). */
  private place(expr: IrExpr): string {
    switch (expr.op) {
      case "local":
        return `l_${expr.name}`;
      case "field":
        return `${this.place(expr.target)}.f_${expr.name}`;
      case "index": {
        const target = this.place(expr.target);
        return `${target}[idx(${this.scalar(expr.index)}, ${target}.len(), "index")?]`;
      }
      case "arrayNew":
      case "arrayLiteral":
      case "mapNew":
      case "struct":
      case "call":
        return `(${this.value(expr, this.typeOf(expr))})`;
      default:
        throw new RustBackendError(`${expr.op} cannot produce reference-typed storage`);
    }
  }

  private string(expr: IrExpr): string {
    switch (expr.op) {
      case "str":
        return `str_literal(&[${[...expr.value].map((_, index) => expr.value.charCodeAt(index)).join(", ")}])`;
      case "slice":
        return `slice(&${this.stringRef(expr.target)}, ${this.scalar(expr.start)}, ${this.scalar(expr.end)})?`;
      case "toLowerAscii":
        return `to_lower_ascii(&${this.stringRef(expr.target)})?`;
      case "cond":
        return `(if ${this.scalar(expr.test)} { ${this.string(expr.then)} } else { ${this.string(expr.otherwise)} })`;
      case "call":
        return this.call(expr);
      case "local":
      case "field":
      case "index":
        return `${this.place(expr)}.clone()`;
      default:
        throw new RustBackendError(`${expr.op} is not a string expression`);
    }
  }

  /** A string expression usable by reference: places are not cloned. */
  private stringRef(expr: IrExpr): string {
    return expr.op === "local" || expr.op === "field" || expr.op === "index" ? this.place(expr) : `(${this.string(expr)})`;
  }

  /** f64 and bool expressions. */
  private scalar(expr: IrExpr): string {
    switch (expr.op) {
      case "num":
        return rustNumber(expr.value);
      case "bool":
        return String(expr.value);
      case "local":
        return `l_${expr.name}`;
      case "binary": {
        const symbol = BINARY[expr.operator];
        if (expr.operator === "eq" || expr.operator === "ne") {
          const type = this.typeOf(expr.left);
          if (type.kind === "string") {
            return `(${this.stringRef(expr.left)} ${symbol} ${this.stringRef(expr.right)})`;
          }
        }
        return `(${this.scalar(expr.left)} ${symbol} ${this.scalar(expr.right)})`;
      }
      case "and":
        return `(${this.scalar(expr.left)} && ${this.scalar(expr.right)})`;
      case "or":
        return `(${this.scalar(expr.left)} || ${this.scalar(expr.right)})`;
      case "not":
        return `(!${this.scalar(expr.operand)})`;
      case "neg":
        return `(-${this.scalar(expr.operand)})`;
      case "cond":
        return `(if ${this.scalar(expr.test)} { ${this.scalar(expr.then)} } else { ${this.scalar(expr.otherwise)} })`;
      case "min":
      case "max": {
        const helper = expr.op === "min" ? "js_min" : "js_max";
        const [first, ...rest] = expr.args.map((arg) => this.scalar(arg));
        return rest.reduce((folded, next) => `${helper}(${folded}, ${next})`, `(${first})`);
      }
      case "length":
        return this.typeOf(expr.target).kind === "string"
          ? `(${this.stringRef(expr.target)}.len() as f64)`
          : `(${this.place(expr.target)}.len() as f64)`;
      case "index": {
        const target = this.typeOf(expr.target);
        const element = `${this.place(expr)}`;
        return target.kind === "array" && target.storage !== "dynamic" && target.storage !== "f64" ? `(${element} as f64)` : element;
      }
      case "charCodeAt":
        return `char_code_at(&${this.stringRef(expr.target)}, ${this.scalar(expr.index)})?`;
      case "mapGetOr":
        return `(match ${this.place(expr.map)}.get(&*${this.stringRef(expr.key)}) { Some(value) => *value, None => ${this.scalar(expr.fallback)} })`;
      case "mapHas":
        return `${this.place(expr.map)}.contains_key(&*${this.stringRef(expr.key)})`;
      case "field":
        return `${this.place(expr)}`;
      case "call":
        return this.call(expr);
      default:
        throw new RustBackendError(`${expr.op} is not a scalar expression`);
    }
  }

  private call(expr: Extract<IrExpr, { op: "call" }>): string {
    const callee = this.functions.get(expr.callee);
    if (!callee) {
      throw new RustBackendError(`unknown callee ${expr.callee}`);
    }
    const args = expr.args.map((arg, index) => {
      const type = callee.params[index]?.type ?? this.typeOf(arg);
      if (isReferenceType(type)) {
        return `&${this.place(arg)}`;
      }
      return type.kind === "string" ? this.string(arg) : this.scalar(arg);
    });
    return `f_${expr.callee}(${["ctx", ...args].join(", ")})?`;
  }

  /** A value converted for storage in an array of `arrayType` (typed stores are checked). */
  private storeValue(expr: IrExpr, arrayType: IrType): string {
    if (arrayType.kind !== "array") {
      throw new RustBackendError("store into a non-array");
    }
    switch (arrayType.storage) {
      case "dynamic":
        return this.value(expr, arrayType.element);
      case "u8":
        return `store_u8(${this.scalar(expr)})?`;
      case "u32":
        return `store_u32(${this.scalar(expr)})?`;
      case "i32":
        return `store_i32(${this.scalar(expr)})?`;
      case "f64":
        return `store_f64(${this.scalar(expr)})?`;
    }
  }

  // --- typing ---------------------------------------------------------------------------------

  typeOf(expr: IrExpr): IrType {
    switch (expr.op) {
      case "num":
      case "neg":
      case "min":
      case "max":
      case "length":
      case "charCodeAt":
      case "mapGetOr":
        return { kind: "f64" };
      case "bool":
      case "and":
      case "or":
      case "not":
      case "mapHas":
        return { kind: "bool" };
      case "binary":
        return ["add", "sub", "mul", "div", "mod"].includes(expr.operator) ? { kind: "f64" } : { kind: "bool" };
      case "str":
      case "slice":
      case "toLowerAscii":
        return { kind: "string" };
      case "local":
        return this.lookup(expr.name);
      case "cond":
        return this.typeOf(expr.then);
      case "index": {
        const target = this.typeOf(expr.target);
        if (target.kind !== "array") {
          throw new RustBackendError("index on a non-array");
        }
        return target.element;
      }
      case "field": {
        const target = this.typeOf(expr.target);
        if (target.kind !== "struct") {
          throw new RustBackendError("field access on a non-struct");
        }
        return this.fieldType(target.name, expr.name);
      }
      case "struct":
        return { kind: "struct", name: expr.name };
      case "arrayNew":
      case "arrayLiteral":
        return expr.type;
      case "mapNew":
        return { kind: "map" };
      case "call": {
        const callee = this.functions.get(expr.callee);
        if (!callee) {
          throw new RustBackendError(`unknown callee ${expr.callee}`);
        }
        return callee.returnType;
      }
    }
  }

  private fieldType(struct: string, field: string): IrType {
    const type = this.structFields.get(struct)?.get(field);
    if (!type) {
      throw new RustBackendError(`unknown field ${struct}.${field}`);
    }
    return type;
  }

  private lookup(name: string): IrType {
    for (let index = this.scopes.length - 1; index >= 0; index -= 1) {
      const type = this.scopes[index]?.get(name);
      if (type) {
        return type;
      }
    }
    throw new RustBackendError(`unbound local ${name}`);
  }

  private localOrigin(name: string): "PARAM" | "FRESH" {
    return this.origins.locals.get(this.current?.name ?? "")?.get(name) ?? "FRESH";
  }

  private originOf(expr: IrExpr): "PARAM" | "FRESH" {
    return this.origins.originOf(this.current?.name ?? "", expr);
  }

  private fresh(label: string): string {
    this.temp += 1;
    return `__${label}${this.temp}`;
  }
}

const BINARY: Readonly<Record<string, string>> = {
  add: "+", sub: "-", mul: "*", div: "/", mod: "%", lt: "<", le: "<=", gt: ">", ge: ">=", eq: "==", ne: "!=",
};

function rustNumber(value: number): string {
  if (!Number.isFinite(value)) {
    return Number.isNaN(value) ? "f64::NAN" : value > 0 ? "f64::INFINITY" : "f64::NEG_INFINITY";
  }
  const text = String(Math.abs(value)).replace("e+", "e");
  const literal = /[.e]/.test(text) ? `${text}_f64` : `${text}.0_f64`;
  return value < 0 || Object.is(value, -0) ? `(-${literal})` : literal;
}

function ownedType(type: IrType): string {
  switch (type.kind) {
    case "f64":
      return "f64";
    case "bool":
      return "bool";
    case "string":
      return "Str";
    case "array":
      return type.storage === "dynamic" ? `Vec<${ownedType(type.element)}>` : `Vec<${type.storage}>`;
    case "map":
      return "HashMap<Str, f64>";
    case "struct":
      return `K_${type.name}`;
    case "void":
      return "()";
  }
}

function paramType(type: IrType): string {
  switch (type.kind) {
    case "array":
      return type.storage === "dynamic" ? `&[${ownedType(type.element)}]` : `&[${type.storage}]`;
    case "map":
      return "&HashMap<Str, f64>";
    case "struct":
      return `&K_${type.name}`;
    default:
      return ownedType(type);
  }
}

function returnType(type: IrType): string {
  return ownedType(type);
}

// --- N-API surface ------------------------------------------------------------------------------

const TYPED_ARRAY_CLASS: Readonly<Record<string, string>> = { u8: "Uint8Array", u32: "Uint32Array", i32: "Int32Array", f64: "Float64Array" };

function napiSurface(request: RustBackendRequest, module: IrModule): string[] {
  const contract = request.contract;
  const handleState = contract.state?.name;
  const sections: string[] = [];
  if (handleState) {
    sections.push(`/// Native state owned by JavaScript; immutable for its lifetime (contract: ${contract.state?.invalidation}).
#[napi(js_name = "${handleState}")]
pub struct H_${handleState} {
  inner: K_${handleState},
}`);
  }
  const entries = [request.prepare?.entry, request.execute.entry].filter((entry): entry is string => entry !== undefined);
  for (const entry of entries) {
    const fn = module.functions.find((candidate) => candidate.name === entry);
    if (!fn) {
      throw new RustBackendError(`missing entry ${entry}`);
    }
    sections.push(napiFunction(fn, handleState));
  }
  return sections;
}

function napiFunction(fn: IrFunction, handleState: string | undefined): string {
  const params: string[] = [];
  const conversions: string[] = [];
  const args: string[] = ["&mut ctx"];
  for (const param of fn.params) {
    const name = `a_${param.name}`;
    const type = param.type;
    if (type.kind === "struct" && type.name === handleState) {
      params.push(`${name}: &H_${handleState}`);
      args.push(`&${name}.inner`);
    } else if (type.kind === "f64" || type.kind === "bool") {
      params.push(`${name}: ${type.kind}`);
      args.push(name);
    } else if (type.kind === "string") {
      params.push(`${name}: Utf16String`);
      args.push(`Rc::from(&*${name})`);
    } else if (type.kind === "array" && type.storage !== "dynamic") {
      params.push(`${name}: ${TYPED_ARRAY_CLASS[type.storage]}`);
      args.push(`&*${name}`);
    } else if (type.kind === "array" && (type.element.kind === "f64" || type.element.kind === "bool")) {
      params.push(`${name}: Vec<${type.element.kind}>`);
      args.push(`&${name}`);
    } else if (type.kind === "array" && type.element.kind === "string") {
      params.push(`${name}: Vec<Utf16String>`);
      conversions.push(`  let c_${param.name}: Vec<Str> = ${name}.iter().map(|text| Rc::from(&**text)).collect();`);
      args.push(`&c_${param.name}`);
    } else {
      throw new RustBackendError(`parameter ${param.name} cannot cross the N-API boundary`);
    }
  }

  const result = fn.returnType;
  let napiReturn: string;
  let convert: string;
  if (result.kind === "struct" && result.name === handleState) {
    napiReturn = `H_${handleState}`;
    convert = `H_${handleState} { inner: value }`;
  } else if (result.kind === "f64" || result.kind === "bool") {
    napiReturn = result.kind;
    convert = "value";
  } else if (result.kind === "string") {
    napiReturn = "Utf16String";
    convert = "Utf16String::from(value.to_vec())";
  } else if (result.kind === "array" && result.storage !== "dynamic") {
    napiReturn = TYPED_ARRAY_CLASS[result.storage] ?? "";
    convert = `${napiReturn}::new(value)`;
  } else if (result.kind === "array" && (result.element.kind === "f64" || result.element.kind === "bool")) {
    napiReturn = `Vec<${result.element.kind}>`;
    convert = "value";
  } else if (result.kind === "array" && result.element.kind === "string") {
    napiReturn = "Vec<Utf16String>";
    convert = "value.iter().map(|text| Utf16String::from(text.to_vec())).collect()";
  } else if (result.kind === "void") {
    napiReturn = "()";
    convert = "value";
  } else {
    throw new RustBackendError(`return type of ${fn.name} cannot cross the N-API boundary`);
  }

  return `#[napi(js_name = "${fn.name}")]
pub fn napi_${fn.name}(${params.join(", ")}) -> napi::Result<${napiReturn}> {
${conversions.join("\n")}${conversions.length > 0 ? "\n" : ""}  let mut ctx = Ctx::new();
  let value = f_${fn.name}(${args.join(", ")}).map_err(trap_error)?;
  Ok(${convert})
}`;
}
