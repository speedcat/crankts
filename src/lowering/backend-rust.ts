/**
 * Rust/N-API backend (v0.2.2, quality pass v0.2.4). Emits a napi-rs crate whose behavior equals
 * `interpretIr`: the same results, and a `CRANKTS_KERNEL_TRAP` error wherever the interpreter raises
 * `KernelTrap`. Internal failures (panics) surface as `CRANKTS_INTERNAL_ERROR` and must not fall back.
 *
 * - Storage follows the verifier's origin analysis: fresh storage is owned, parameter-derived
 *   storage is borrowed. NO_ALIASING makes owned values equivalent to JavaScript references.
 * - Numbers proven INT by {@link analyzeIntegers} are i64 with arithmetic checked to |v| <= 2^53,
 *   so they always equal the JS f64 values; everything else stays f64 with checked conversions.
 * - Non-escaping arrays allocated inside loops reuse one buffer per allocation site.
 * - Strings are `Rc<[u16]>`: every position is a UTF-16 code unit, exactly as in JS.
 */

export interface RustCrate {
  readonly files: ReadonlyMap<string, string>;
}

export interface RustBackendRequest {
  readonly crateName: string;
  readonly contract: KernelContract;
  readonly execute: IrModule;
  readonly prepare?: IrModule;
}

export class RustBackendError extends Error {}

export const KERNEL_TRAP_PREFIX = "CRANKTS_KERNEL_TRAP";
export const INTERNAL_ERROR_PREFIX = "CRANKTS_INTERNAL_ERROR";
const NAPI_VERSION = "3.14.2";
const NAPI_DERIVE_VERSION = "3.6.12";

export function emitRustCrate(request: RustBackendRequest): RustCrate {
  const module = request.prepare ? mergeModules(request.execute, request.prepare) : request.execute;
  const entries = [request.execute.entry, ...(request.prepare ? [request.prepare.entry] : [])];
  const emitter = new RustEmitter(module, analyzeOrigins(module), analyzeIntegers(module, entries));
  const lines = [
    "// Generated by CrankTS (Rust/N-API backend). Do not edit; regenerate with `crankts extract`.",
    `// Contract: ${request.contract.name} (${request.contract.shape})`,
    RUNTIME,
    ...module.structs.map((struct) => emitter.struct(struct)),
    ...module.functions.map((fn) => emitter.function(fn)),
    ...napiSurface(request, module, emitter),
  ];
  return {
    files: new Map([
      ["Cargo.toml", cargoToml(request.crateName)],
      ["src/lib.rs", `${lines.join("\n\n")}\n`],
    ]),
  };
}

