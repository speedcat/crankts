import { relative, resolve, sep } from "node:path";
import type { InternPlan } from "./interning.js";
import { wrapperRuntime } from "./wrapper-ts.js";

/**
 * Integration and parity generation for id-packed kernels (v0.2.6).
 *
 * `ts/integration.ts` exports `<name>(original, ...args)`, called by the patched source. It packs the
 * arguments (pack guards → run the original), then runs the native kernel if the addon is loaded
 * and the packed TypeScript otherwise, and unpacks the result. A kernel trap runs the original;
 * any other failure is rethrown as CRANKTS_INTERNAL_ERROR. `variants` exposes the original, packed
 * TypeScript, and native paths separately for the A/B/C measurement.
 */

export interface InternIntegrationRequest {
  readonly plan: InternPlan;
  readonly crateName: string;
  /** Absolute path of the generated `ts/` directory (to re-point the original type imports). */
  readonly tsDirectory: string;
}

export function emitInternIntegration(request: InternIntegrationRequest): ReadonlyMap<string, string> {
  const { plan } = request;
  const library = request.crateName.replace(/-/g, "_");
  const envVariable = `CRANKTS_ADDON_${library.toUpperCase()}`;
  const typeImports = plan.typeImports.map(({ specifier, text }) => {
    if (!specifier.startsWith(".")) return text;
    let target = relative(request.tsDirectory, resolve(plan.sourceDirectory, specifier)).split(sep).join("/");
    if (!target.startsWith(".")) target = `./${target}`;
    return text.replace(JSON.stringify(specifier), JSON.stringify(target)).replace(`'${specifier}'`, JSON.stringify(target));
  });
  const name = plan.function;
  const pascal = name.charAt(0).toUpperCase() + name.slice(1);

  const packed = `// Generated by CrankTS (v0.2.6 id-domain representation pass) from ${name}. Do not edit; regenerate with \`crankts extract --intern\`.
// The "transformed TypeScript" variant: same algorithm over interned indices, CSR, bitmaps, and ranks.
// It is also the source lowered to the Kernel IR and the native kernel.

${plan.packedFunction}
`;

  const adapters = `// Generated by CrankTS (v0.2.6). Pack/unpack adapters for ${name}; every assumption of the packed form is
// checked here (PackingGuard → the caller runs the original function).
${typeImports.join("\n")}

${plan.adapters}
`;

  const integration = `// Generated by CrankTS (v0.2.6 packed-kernel integration). Do not edit; regenerate with \`crankts extract --intern\`.
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { ${plan.packedName} } from "./packed.js";
export { sealedGraphStats } from "./adapters.js";
import { pack${pascal}, PackingGuard${plan.output === "idArrays" ? `, unpack${pascal}` : ""} } from "./adapters.js";

${wrapperRuntime(library, envVariable, false)}

/** Calls served by the packed TypeScript (no addon) and packing guards that ran the original. */
export const packedStatus = { packedTypeScriptCalls: 0, packingGuards: 0 };

type Original = (...args: never[]) => unknown;

const unpack = (result: unknown, ids: readonly string[]): unknown => ${plan.output === "idArrays" ? `unpack${pascal}(result as ArrayLike<number>, ids)` : "result"};

/** The three variants, separately (A original, B packed TypeScript, C native), for measurements. */
export const variants = {
  packedTypeScript: (...args: unknown[]): unknown => {
    const packed = (pack${pascal} as (...values: unknown[]) => { ids: readonly string[]; args: readonly unknown[] })(...args);
    return unpack((${plan.packedName} as (...values: unknown[]) => unknown)(...packed.args), packed.ids);
  },
  native: (...args: unknown[]): unknown => {
    const packed = (pack${pascal} as (...values: unknown[]) => { ids: readonly string[]; args: readonly unknown[] })(...args);
    const kernel = nativeAddon?.["${plan.packedName}"];
    if (!kernel) throw new Error("addon not loaded");
    return unpack(kernel(...packed.args), packed.ids);
  },
  pack: pack${pascal} as (...values: unknown[]) => { ids: readonly string[]; args: readonly unknown[] },
  packedKernel: ${plan.packedName} as (...values: unknown[]) => unknown,
};

export function ${name}<F extends Original>(original: F, ...args: Parameters<F>): ReturnType<F> {
  let packed: { ids: readonly string[]; args: readonly unknown[] };
  try {
    packed = (pack${pascal} as (...values: unknown[]) => { ids: readonly string[]; args: readonly unknown[] })(...args);
  } catch (error) {
    if (error instanceof PackingGuard) {
      packedStatus.packingGuards += 1;
      return original(...args) as ReturnType<F>;
    }
    throw error;
  }
  const kernel = nativeAddon?.["${plan.packedName}"];
  if (kernel) {
    try {
      const result = kernel(...packed.args);
      nativeStatus.nativeCalls += 1;
      return unpack(result, packed.ids) as ReturnType<F>;
    } catch (error) {
      handleNativeFailure(error, "${plan.packedName}");
      return original(...args) as ReturnType<F>;
    }
  }
  packedStatus.packedTypeScriptCalls += 1;
  return unpack((${plan.packedName} as (...values: unknown[]) => unknown)(...packed.args), packed.ids) as ReturnType<F>;
}
`;

  const roles = plan.params.map((role) => role.role);
  const parity = `// Generated by CrankTS (v0.2.6 packed-kernel parity runner). Do not edit; regenerate with \`crankts extract --intern\`.
// Random inputs for the original signature (universe, graph, entity lookup); for every case the original,
// the packed TypeScript, and the native kernel (when loaded) must agree, or a packing guard must fire.
// Run: node --import tsx parity.ts --module <original module> [--iterations 1000] [--seed 1]
import { pathToFileURL } from "node:url";
import { PackingGuard } from "./adapters.js";
import { nativeAddon, variants } from "./integration.js";

const ROLES = ${JSON.stringify(roles)} as const;
const FIELDS = ${JSON.stringify(plan.entityFields)} as const;

export interface PackedParityReport {
  readonly cases: number;
  readonly packedAgreed: number;
  readonly nativeAgreed: number;
  readonly packingGuards: number;
  readonly mismatches: readonly string[];
}

function random(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state * 1664525 + 1013904223) >>> 0;
    return state / 2 ** 32;
  };
}

function generate(next: () => number): unknown[] {
  const count = Math.floor(next() * 30);
  const ids = Array.from({ length: count }, (_, index) => \`f\${(index * 7919) % 1000}\`);
  const entities = ids.map((id) => ({
    id,
    ...Object.fromEntries(FIELDS.map((field) => [field.field, field.kind === "locale" ? ["a.ts", "b.ts", "B.ts", "c/d.ts"][Math.floor(next() * 4)] : 1 + Math.floor(next() * 5)])),
  }));
  const adjacency = new Map<string, Set<string>>(ids.map((id) => [id, new Set<string>()]));
  for (let edge = Math.floor(next() * count * 1.5); edge > 0; edge -= 1) {
    const left = ids[Math.floor(next() * count)];
    const right = ids[Math.floor(next() * count)];
    if (left !== undefined && right !== undefined) {
      adjacency.get(left)?.add(right);
      adjacency.get(right)?.add(left);
    }
  }
  if (count > 0 && next() < 0.05) adjacency.get(ids[0] as string)?.add("outside");
  const lookup = new Map(entities.map((entity) => [entity.id, entity]));
  if (count > 0 && next() < 0.05) lookup.delete(ids[count - 1] as string);
  return ROLES.map((role) => (role === "universe" ? entities : role === "graph" ? adjacency : role === "entityRank" ? lookup : 0));
}

export function runPackedParity(original: (...args: unknown[]) => unknown, options: { iterations?: number; seed?: number } = {}): PackedParityReport {
  const next = random(options.seed ?? 1);
  let packedAgreed = 0;
  let nativeAgreed = 0;
  let packingGuards = 0;
  const mismatches: string[] = [];
  const iterations = options.iterations ?? 1000;
  for (let iteration = 0; iteration < iterations; iteration += 1) {
    const args = generate(next);
    const expected = JSON.stringify(original(...args));
    try {
      if (JSON.stringify(variants.packedTypeScript(...args)) === expected) packedAgreed += 1;
      else mismatches.push(\`packed TypeScript, case \${iteration}\`);
      if (nativeAddon) {
        if (JSON.stringify(variants.native(...args)) === expected) nativeAgreed += 1;
        else mismatches.push(\`native, case \${iteration}\`);
      }
    } catch (error) {
      if (error instanceof PackingGuard) packingGuards += 1;
      else mismatches.push(\`case \${iteration}: \${error instanceof Error ? error.message : String(error)}\`);
    }
  }
  return { cases: iterations, packedAgreed, nativeAgreed, packingGuards, mismatches };
}

async function main(): Promise<void> {
  const argv = process.argv.slice(2);
  const option = (flag: string): string | undefined => argv[argv.indexOf(flag) + 1];
  const module = await import(pathToFileURL(option("--module") ?? "").href) as Record<string, (...args: unknown[]) => unknown>;
  const original = module["${name}"];
  if (!original) throw new Error("--module must export ${name}");
  const report = runPackedParity(original, { iterations: Number(option("--iterations") ?? 1000), seed: Number(option("--seed") ?? 1) });
  console.log(JSON.stringify({ ...report, mismatches: report.mismatches.slice(0, 5) }, null, 2));
  process.exitCode = report.mismatches.length > 0 ? 1 : 0;
}

// No top-level await: the generated directory may be loaded as CommonJS.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  void main();
}
`;

  return new Map([
    ["ts/packed.ts", packed],
    ["ts/adapters.ts", adapters],
    ["ts/integration.ts", integration],
    ["ts/parity.ts", parity],
  ]);
}
